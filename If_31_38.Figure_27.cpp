int main() {
    // Налаштування локалізації для української мови в консолі
    std::setlocale(LC_ALL, "Ukranian");

    double x;
    int g;

    // Введення дійсного числа x
    std::cout << "Введіть дійсне число x: ";
    std::cin >> x;

    // Обчислення значення функції g(x) за гілками умов
    if (x < -1) {
        g = static_cast<int>(x + 1);
    } 
    else if (x >= -1 && x <= 1) {
        g = static_cast<int>(x * x - 1);
    } 
    else { // x > 1
        g = 3;
    }

    // Виведення результату
    std::cout << "Значення функції g(x) = " << g << std::endl;

    return 0;
}

