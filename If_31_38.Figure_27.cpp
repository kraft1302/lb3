#include <iostream>

int main() {
    // Налаштування локалізації для коректного відображення української мови в консолі
    std::setlocale(LC_ALL, "Ukranian");

    double r, x, y;

    // Введення початкових даних
    std::cout << "Введіть радіус кола (r > 0): ";
    std::cin >> r;

    std::cout << "Введіть координату x точки: ";
    std::cin >> x;

    std::cout << "Введіть координату y точки: ";
    std::cin >> y;

    // Перевірка умови належності точки зафарбованій області (Варіант 27)
    // 1. y >= 0 — точка знаходиться не нижче осі x
    // 2. y <= x + 2*r — точка лежить нижче/правіше лівої похилої межі
    // 3. y <= -x — точка лежить нижче/лівіше правої похилої межі
    if (y >= 0 && y <= (x + 2 * r) && y <= -x) {
        std::cout << "Результат: Точка ПОТРАПЛЯЄ в область (Зона Варіанта 27)" << std::endl;
    } else {
        std::cout << "Результат: Точка НЕ потрапляє в область" << std::endl;
    }

    return 0;
}
